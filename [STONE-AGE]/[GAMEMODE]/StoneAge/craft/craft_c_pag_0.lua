if itemname == "Selecione algum item" then outputChatBox(itemname..'!',255,0,0) return end
if itemname == "Cama" and getElementData(localPlayer,"cama") then outputChatBox("Você já tem uma cama!",255,0,0) return end
item1 = guiGetText(nome_requerimento_0[1])
get_item_1 = getElementData(localPlayer,item1)
