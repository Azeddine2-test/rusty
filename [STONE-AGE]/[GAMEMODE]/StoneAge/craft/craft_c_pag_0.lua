										setElementData(tempOb[localPlayer],"item2",item2)
										setElementData(tempOb[localPlayer],"item3",item3)
										setElementData(tempOb[localPlayer],"item4",item4)
										setElementData(tempOb[localPlayer],"item5",item5)
										setElementData(tempOb[localPlayer],"item6",item6)
										guiSetVisible(window_craft,false)					
									end
					else
					if isAmmo(itemname) then
					setElementData(localPlayer,itemname,getElementData(localPlayer,itemname) +getAmmoQuantByName(itemname))
					outputChatBox('Você craftou '..itemname..' x'..getAmmoQuantByName(itemname)..'!',255,255,0)
					else
					setElementData(localPlayer,itemname,getElementData(localPlayer,itemname) +1)
					outputChatBox('Você craftou um '..itemname..'!',255,255,0)
					end
					setElementData(localPlayer,item1,get_item_1-max1)
					setElementData(localPlayer,item2,get_item_2-max2)
					setElementData(localPlayer,item3,get_item_3-max3)
					setElementData(localPlayer,item4,get_item_4-max4)
					setElementData(localPlayer,item5,get_item_5-max5)
					setElementData(localPlayer,item6,get_item_6-max6)
					hide_craft()
					showCursor(false)
					end
			else
			outputChatBox("Você precisa de mais ["..item6.."] para craftar ["..itemname.."]",255,0,0)
			return
			end					
			else
			outputChatBox("Você precisa de mais ["..item5.."] para craftar ["..itemname.."]",255,0,0)
			return
			end				
			else
			outputChatBox("Você precisa de mais ["..item4.."] para craftar ["..itemname.."]",255,0,0)
			return
			end		
			else
			outputChatBox("Você precisa de mais ["..item3.."] para craftar ["..itemname.."]",255,0,0)
			return
			end
		else
		outputChatBox("Você precisa de mais ["..item2.."] para craftar ["..itemname.."]",255,0,0)
		return
		end
	else
	outputChatBox("Você precisa de mais ["..item1.."] para craftar ["..itemname.."]",255,0,0)
	return
	end
end


