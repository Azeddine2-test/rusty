porcento_exp = (experiencia*100)/experiencia_need
guiSetText(exp_label,"Exp: "..getElementData(localPlayer,"experiencia").."/"..getElementData(localPlayer,"experiencia_need")..' '..porcento_exp..'%')
if porcento_exp >= 0 and porcento_exp < 10 then
barra =  'barra'
elseif porcento_exp >= 10 and porcento_exp < 20 then
barra =  'barra_10'
elseif porcento_exp >= 20 and porcento_exp < 30 then
barra =  'barra_20'
elseif porcento_exp >= 30 and porcento_exp < 40  then
barra =  'barra_30'
elseif porcento_exp >= 40 and porcento_exp < 50 then
barra =  'barra_40'
elseif porcento_exp >= 50 and porcento_exp < 60 then
