toggleinv = function(key,keyState)
	animation, block  = getPedAnimation(localPlayer)
if animation and animation ~= 'BOMBER' and block ~= 'bom_plant_loop' then 
outputChatBox('Não é possivel abrir o inventario durante animação.',255,0,0)
hideInventoryManual()
return 
end

if getElementData(localPlayer,'logedin') then 
if getElementData(localPlayer,'cant_open_inventory') then outputChatBox('Aguarde até o fim da ação atual.',255,255,0) return end
			if isPlayerInLoot() then
				box = getElementData(getLocalPlayer(),"currentCol")
					if isPlayerInBox() and getElementData(box,"password") ~= false and getElementData(box,"password") ~= 0 then 
						if guiGetVisible(window_inventory) == true then
						hideInventoryManual()
						return
						end
						if getElementData(localPlayer,"accountName") == getElementData(box,"creator") then
						guiSetVisible(button_set_box_pass,true)
						else
						guiSetVisible(button_set_box_pass,false)
						end
						guiSetVisible(box_window_check,not guiGetVisible(box_window_check))
						lock_unlock(box_window_check)
						
						showCursor(not isCursorShowing())
						onClientOpenInventoryStopMenu ()
						return	
					end
				if isPlayerInBox() and getElementData(box,"password") == 0 and getElementData(localPlayer,"accountName") == getElementData(box,"creator") then 
				guiSetVisible(button_set_box_pass, true)
				else
				guiSetVisible(button_set_box_pass, false)			
				end
			guiSetVisible(window_loot,true)
			col = getElementData(getLocalPlayer(),"currentCol")
			gearName = getElementData(getLocalPlayer(),"lootname")
			refreshLoot(col,gearName)
			end
		refreshInventory()
		drawInfoInventory()
		triggerServerEvent("backpackGroundOpen", getLocalPlayer())
		guiSetVisible(window_inventory,not guiGetVisible(window_inventory))
		guiSetVisible(window_centro,not guiGetVisible(window_centro))
        if guiGetVisible(window_inventory) == true then
            onClientOpenInventoryStopMenu()
			triggerEvent('hide_group_window',localPlayer)
			triggerEvent('hide_config_window',localPlayer)
			triggerEvent('hide_admin_window',localPlayer)
			triggerEvent('hide_craft_window',localPlayer)
			triggerEvent('hide_help_window',localPlayer)
			triggerEvent('hide_confirm_window',localPlayer)
		updateLabels()
		showCursor(true)
        else
			showCursor(false)
            hideRightClickInventoryMenu ()
			guiSetVisible(box_window_check,false)
			guiSetVisible(window_loot,false)
			guiSetVisible(box_window_change,false)
			guiSetVisible(window_info_loot,false)
			guiSetVisible(window_info_inventory,false)
			guiSetVisible(button_set_box_pass,false)
			if animation then 
			triggerServerEvent("backpackGroundClose", getLocalPlayer())
			end
        end	
end
end
