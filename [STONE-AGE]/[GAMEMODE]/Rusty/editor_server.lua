function onJoin ( )
	local joinedPlayerName = getPlayerName ( source )
	local game = getGameType()
	outputChatBox ( joinedPlayerName..", bem vindo à "..game.."!",source, 255, 255, 255 )
	for i, data in ipairs(getElementsByType('player')) do 
	if source ~= data then
	outputChatBox ( joinedPlayerName.." entrou no servidor!",data, 255, 255, 255 )
	end
	end
end
